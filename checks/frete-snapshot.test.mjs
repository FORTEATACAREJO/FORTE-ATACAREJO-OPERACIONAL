test('promoção em memória é idempotente, não sobrescreve e o rollback preserva o legado',async()=>{
 const lote=loteSintetico();
 const adaptado=await adaptarSnapshots(lote,{empresaId});
 const seco=await aplicarPromocao({fc_motoristas:[],fc_veiculos:[]},adaptado,{aplicar:true,gates:{...gates,aprovacaoHumana:false}});
 assert.equal(seco.escreve,false);
 const primeira=await aplicarPromocao({fc_motoristas:[],fc_veiculos:[]},adaptado,{aplicar:true,gates});
 assert.equal(primeira.escreve,true);
 assert.equal(primeira.destino.fc_motoristas.length,2);
 assert.equal(primeira.destino.fc_veiculos.length,2);
 assert.equal(primeira.destino.fc_motoristas.every(item=>item.ativo===false),true);
 const segunda=await aplicarPromocao(primeira.destino,adaptado,{aplicar:true,gates});
 assert.equal(segunda.destino.fc_motoristas.length,2);
 assert.equal(segunda.inseridos,0);
 const conflito=structuredClone(primeira.destino);
 conflito.fc_motoristas[0].hash='outro';
 const bloqueado=await aplicarPromocao(conflito,adaptado,{aplicar:true,gates});
 assert.equal(bloqueado.escreve,false);
 assert.equal(bloqueado.destino.fc_motoristas[0].hash,'outro');
 const liberado=structuredClone(primeira.destino);
 liberado.fc_motoristas[0].ativo=true;
 const promovidos=adaptado.prontos.filter(item=>item.entidade==='motorista'||item.entidade==='veiculo');
 const rollback=ensaiarRollback({legado:lote,operacional:liberado,promovidos});
 assert.equal(rollback.legadoIntacto,true);
 assert.equal(rollback.exclusaoLegado,false);
 assert.equal(rollback.restaurado.fc_motoristas.length,1);
 assert.equal(rollback.restaurado.fc_motoristas[0].ativo,true);
 assert.equal(rollback.restaurado.fc_veiculos.length,0);
 assert.equal(permitirExclusaoLegado({backupRestauravel:true,aprovacaoHumana:true}).permitido,false);
});
